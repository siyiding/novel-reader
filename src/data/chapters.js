// 动态导入章节内容
export async function loadChapterContent(chapterId) {
  try {
    const response = await fetch(`./chapters/${String(chapterId).padStart(3, '0')}.md`);
    if (!response.ok) throw new Error('Failed to load');
    const text = await response.text();
    // 简单解析markdown
    return parseMarkdown(text);
  } catch (e) {
    return { title: `第${chapterId}章`, content: '<p>章节内容加载中...</p>' };
  }
}

function parseMarkdown(md) {
  const lines = md.split('\n');
  let title = '';
  let content = [];
  let inParagraph = false;

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed) {
      if (inParagraph) {
        content.push('</p>');
        inParagraph = false;
      }
      continue;
    }

    if (trimmed.startsWith('# ')) {
      title = trimmed.replace('# ', '');
    } else if (trimmed.startsWith('## ')) {
      if (inParagraph) {
        content.push('</p>');
        inParagraph = false;
      }
      content.push(`<h2>${trimmed.replace('## ', '')}</h2>`);
    } else if (trimmed.startsWith('### ')) {
      if (inParagraph) {
        content.push('</p>');
        inParagraph = false;
      }
      content.push(`<h3>${trimmed.replace('### ', '')}</h3>`);
    } else if (trimmed.startsWith('---')) {
      if (inParagraph) {
        content.push('</p>');
        inParagraph = false;
      }
      content.push('<hr>');
    } else {
      if (!inParagraph) {
        content.push('<p>');
        inParagraph = true;
      }
      content.push(trimmed);
    }
  }

  if (inParagraph) {
    content.push('</p>');
  }

  return { title, content: content.join('\n') };
}
